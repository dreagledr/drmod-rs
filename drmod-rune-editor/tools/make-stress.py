#!/usr/bin/env python3
"""Generate a long, valid `.tas` script for editor stress tests.

The generated file is not a run worth playing: it is a deterministic sweep with the whole DSL
vocabulary on screen, enough lines to make the text area lay out a lot, and enough frames to make
the command table virtualise a lot. The mod's frame limit is 1 000 000.

    python3 tools/make-stress.py --lines 4000 --spacing 100 --out examples/stress-long.tas

The script is valid `.tas` (the editor's parser is the check): one rules line, then frame lines
with unique tokens, comments, blank markers and a mix of absolute and `+delta` frame numbers.
"""

from __future__ import annotations

import argparse
from pathlib import Path

# A sweep around the compass and through the pad, one shape per line. Tokens are the DSL's own.
LINES = [
    "lsx:{x}:2 lsy:{y}:2 a:2",
    "ls:{angle}:2 rt:2",
    "lsx:{x}:3 lsy:{y}:3 y:3",
    "rs:{angle}:3 x:3",
    "y:2 b:2 lr:2",
    "rsx:{x}:2 rsy:{y}:2 lt:2",
    "r:1 ax:1",
    "lb:1 rb:1",
    "du:1 dl:1",
    "mu:1 md:1 ml:1 mr:1",
]


def generate(lines: int, spacing: int) -> str:
    if lines < 1:
        raise SystemExit("--lines must be positive")
    if spacing < 1:
        raise SystemExit("--spacing must be positive")
    if (lines - 1) * spacing >= 1_000_000:
        raise SystemExit("the last frame would exceed the mod's 1 000 000 limit")

    out = [
        "# stress-long.tas — generated by tools/make-stress.py, not a run to play.",
        "# The sweep exists to make the editor draw a lot of text and a lot of table rows.",
        "! name=stress-long trig=ticks:0",
    ]

    for i in range(lines):
        frame = i * spacing
        if i and i % 250 == 0:
            out.append(f"# {i} lines, frame {frame}")
        if i and i % 17 == 0:
            out.append(str(frame))
            continue

        shape = LINES[i % len(LINES)]
        x = ((i * 37) % 2001) - 1000
        y = ((i * 53) % 2001) - 1000
        angle = (i * 17) % 360
        tokens = shape.format(x=x, y=y, angle=angle)
        # Every seventh frame line is relative, so both spellings of the first token are parsed.
        first = str(frame) if i == 0 or i % 7 != 0 else f"+{spacing}"
        out.append(f"{first} {tokens}")

    return "\n".join(out) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--lines", type=int, default=4000)
    parser.add_argument("--spacing", type=int, default=100)
    parser.add_argument("--out", type=Path, default=Path("examples/stress-long.tas"))
    args = parser.parse_args()

    text = generate(args.lines, args.spacing)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(text, encoding="utf-8")

    frames = (args.lines - 1) * args.spacing
    print(
        f"{args.out}: {args.lines} frame lines ({len(text.splitlines())} lines total), "
        f"last frame {frames}, {len(text)} bytes"
    )


if __name__ == "__main__":
    main()
